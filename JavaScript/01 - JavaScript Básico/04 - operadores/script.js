/* Aritméticos 
    + (Adição/Concatenação) - * /
    ** Potenciaçõa
    % Resto da divisão
*/

const num1 = 5
const num2 = 10
console.log(num1/num2); 


/*
    ++ Incremento (pré - incrementa e mostra resultado, pós - mostra resultado depois incrementa)
    -- Decremento (pré - incrementa e mostra resultado, pós - mostra resultado depois incrementa)
    += -= *= /= **= Operadores de atribuição
*/

let num1 = 5
let num2 = 10
num1++
num2--
console.log(num1, num2); 

const add = 5
let num = 10
num += add
console.log(num); 

const add = 5
let num = 10
num -= add
console.log(num); 

const add = 5
let num = 10
num *= add
console.log(num); 

const add = 5
let num = 10
num /= add
console.log(num); 



/*
    parseInt => Transforma em inteiro
    parseFloat => Transforma em decimais
    Number => converte automaticamente
*/

const num1 = 5
const num2 = parseInt ('10')
console.log(num1 + num2); 

const num1 = 5
const num2 = parseFloat('10.8')
console.log(num1 + num2); 

const num1 = 5
const num2 = Number('10')
console.log(num1 + num2); 


