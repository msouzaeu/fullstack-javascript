/**
 * Operadores de comparação
 * 
 * > maio que
 * >= maior ou igual
 * < menor que
 * <= menor ou igual
 * === igualdade estrita (valor e tipo)
 * !== diferente estritra
 * 
 */


console.log(10 > 5);
console.log(10 <5);
console.log(10 >= 5);
console.log(10 <= 5);
console.log(10 === 5);
console.log(10 !== 5);


